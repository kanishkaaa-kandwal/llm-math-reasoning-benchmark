import sympy as sp

# Define variable
x = sp.Symbol('x')

# Problem: Integral of x * exp(-x) from 0 to infinity
function = x * sp.exp(-x)
correct_answer = sp.integrate(function, (x, 0, sp.oo))

print("--- AI Solution Verification ---")
print("Expected Mathematical Output:", correct_answer)

# Verify if correct answer is 1
if correct_answer == 1:
    print("Verification Status: PASSED")
else:
    print("Verification Status: FAILED")